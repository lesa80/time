import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const catalog = JSON.parse(fs.readFileSync(path.join(root, 'themes.json')));
const definitions = { ...catalog, themes: catalog.themes.map(theme => ({ ...theme,
  spec: JSON.parse(fs.readFileSync(path.join(root, theme.sourceSpec))) })) };
fs.writeFileSync(path.join(root, 'themes-data.mjs'), `// Generated by scripts/build-preview.mjs\nexport default ${JSON.stringify(definitions, null, 2)};\n`);
const clock = fs.readFileSync(path.join(root, 'time.mjs'), 'utf8').replace(/^export /gm, '');
const preview = fs.readFileSync(path.join(root, 'preview.mjs'), 'utf8').replace(/^import .*;\n/gm, '');
// A classic script with embedded theme specifications also works from file://.
// No module fetch, server, JSON fetch, or browser-specific file permission needed.
fs.writeFileSync(path.join(root, 'preview.js'), `// Generated by scripts/build-preview.mjs\n(async () => {\nconst themeDefinitions = ${JSON.stringify(definitions)};\n${clock}\n${preview}\n})();\n`);
console.log('Bundled browser preview with all catalog themes; supports direct index.html opening.');
